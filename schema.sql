-- 1. Offices / Agencies Table
CREATE TABLE IF NOT EXISTS offices (
    office_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Office certificate signatories.
-- Multiple active signatories can belong to one office; one can be marked as default.
CREATE TABLE IF NOT EXISTS tbl_signatory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id BIGINT NOT NULL REFERENCES offices(office_id) ON DELETE CASCADE,
    label TEXT,
    name TEXT NOT NULL,
    position TEXT NOT NULL,
    esig_link TEXT,
    header TEXT,
    sub_header TEXT,
    address TEXT,
    website TEXT,
    footer TEXT,
    post_nominals TEXT,
    certificate_template_variant TEXT DEFAULT 'with_serial' CHECK (certificate_template_variant IN ('with_serial', 'without_serial')),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE tbl_signatory
    ADD COLUMN IF NOT EXISTS label TEXT,
    ADD COLUMN IF NOT EXISTS is_default BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS sort_order INTEGER NOT NULL DEFAULT 0;

DO $$
DECLARE
    constraint_name text;
BEGIN
    SELECT con.conname
    INTO constraint_name
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
    WHERE rel.relname = 'tbl_signatory'
      AND nsp.nspname = 'public'
      AND con.contype = 'u'
      AND array_length(con.conkey, 1) = 1
      AND con.conkey[1] = (
          SELECT attnum
          FROM pg_attribute
          WHERE attrelid = rel.oid
            AND attname = 'office_id'
      )
    LIMIT 1;

    IF constraint_name IS NOT NULL THEN
        EXECUTE format('ALTER TABLE public.tbl_signatory DROP CONSTRAINT %I', constraint_name);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS tbl_signatory_one_default_per_office
    ON tbl_signatory(office_id)
    WHERE is_default = TRUE AND active = TRUE;

CREATE INDEX IF NOT EXISTS tbl_signatory_office_active_idx
    ON tbl_signatory(office_id, active, sort_order);

